function createBsCpeCurriculum(): Curriculum {
  const drafts = courseRows.split('\n').map((row) => {
    const [code, title, units, originalTermId, prerequisites = '', laboratories = ''] = row.split('|');
    return {
      code,
      title,
      units: Number(units),
      originalTermId,
      prerequisites: prerequisites ? prerequisites.split(',') : [],
      linkedLaboratories: laboratories ? laboratories.split(',') : [],
      description: 'A course description is not included in the official program curriculum.',
    };
  });
  const reverseLabs = new Map<string, string[]>();
  drafts.forEach((course) => course.linkedLaboratories.forEach((lab) => {
    reverseLabs.set(lab, [...(reverseLabs.get(lab) ?? []), course.code]);
  }));
  const courses: Course[] = drafts.map((course) => ({
    ...course,
    corequisites: [...new Set([...course.linkedLaboratories, ...(reverseLabs.get(course.code) ?? [])])],
  }));
  return applyKnownCurriculumRules({
    id: 'feutech-cpe-9034c32b',
    program: 'BS Computer Engineering',
    school: 'FEU Institute of Technology',
    sourceFileName: 'Built-in FEU Tech BSCpE curriculum',
    importedAt: '2026-01-01T00:00:00.000Z',
    terms,
    courses,
    fingerprint: '9034c32b',
  });
}

export const supportedPrograms: SupportedProgram[] = [
  {
    id: 'feu-bs-cpe',
    code: 'BSCpE',
    name: 'Bachelor of Science in Computer Engineering',
    school: 'FEU Institute of Technology',
    curriculum: createBsCpeCurriculum(),
  },
];

export function curriculumForProgram(programId: string): Curriculum | null {
  const curriculum = supportedPrograms.find((program) => program.id === programId)?.curriculum;
  return curriculum ? JSON.parse(JSON.stringify(curriculum)) as Curriculum : null;
}
